/**
 * 纯文本 / 段落分章时，判断一行是不是章节标题。
 *
 * 支持这些常见写法：
 *   第一章 异界来客、序章、楔子
 *   1、异界来客
 *   1. 异界来客
 *   一、异界来客
 */

const CHAPTER_TITLE =
  /^\s*(?:第[0-9０-９一二三四五六七八九十百千两零〇]+[章节回卷篇][^\n。！？]{0,20}|序章[^\n。！？]{0,20}|楔子[^\n。！？]{0,20}|(?:[0-9０-９]{1,4}|[一二三四五六七八九十百千两零〇]{1,8})\s*[、.．]\s*(?=[^\s\d])[^\n。！？]{1,30})\s*$/

export const isChapterTitle = (value) => CHAPTER_TITLE.test(String(value ?? ''))
